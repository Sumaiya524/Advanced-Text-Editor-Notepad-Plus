    private void jMenuItem29ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jMenuItem29ActionPerformed
        // TODO add your handling code here:
        
        String[] colors = {"Yellow", "Light Green", "Light Blue", "Pink", "Orange"};
        String choice = (String) javax.swing.JOptionPane.showInputDialog(this, 
                "Choose Highlight Color:", "Highlight", 
                javax.swing.JOptionPane.QUESTION_MESSAGE, null, colors, colors[0]);

        if (choice != null) {
            java.awt.Color selectedColor;

            switch (choice) {
                case "Light Green": selectedColor = new java.awt.Color(144, 238, 144); break;
                case "Light Blue": selectedColor = new java.awt.Color(173, 216, 230); break;
                case "Pink": selectedColor = java.awt.Color.PINK; break;
                case "Orange": selectedColor = java.awt.Color.ORANGE; break;
                default: selectedColor = java.awt.Color.YELLOW; // Default Yellow
            }

            // Tumi je code-ti diyecho shetar update:
            // Selection color set kora (text select korle kemon dekhabe)
            output1.setSelectionColor(selectedColor);
            output1.setSelectedTextColor(java.awt.Color.BLACK);


            try {
                javax.swing.text.DefaultHighlighter.DefaultHighlightPainter painter = 
                    new javax.swing.text.DefaultHighlighter.DefaultHighlightPainter(selectedColor);
                output1.getHighlighter().addHighlight(
                    output1.getSelectionStart(), 
                    output1.getSelectionEnd(), 
                    painter
                );
            } catch (javax.swing.text.BadLocationException e) {
                // Error handling
            }
        }
        
    }//GEN-LAST:event_jMenuItem29ActionPerformed

