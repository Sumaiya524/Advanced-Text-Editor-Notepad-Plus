    private void jMenuItem28ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jMenuItem28ActionPerformed
        // TODO add your handling code here:
        JFrame previewFrame = new JFrame("Markdown Live Preview");
        previewFrame.setSize(600, 500);
        previewFrame.setLayout(new BorderLayout());

        JEditorPane previewPane = new JEditorPane();
        previewPane.setContentType("text/html");
        previewPane.setEditable(false);
        previewFrame.add(new JScrollPane(previewPane), BorderLayout.CENTER);

        String text = output1.getText();

        String html = text
            .replaceAll("(?m)^# (.*)$", "<h1>$1</h1>")      // # Heading 1
            .replaceAll("(?m)^## (.*)$", "<h2>$1</h2>")     // ## Heading 2
            .replaceAll("\\*\\*(.*?)\\*\\*", "<b>$1</b>")   // **Bold**
            .replaceAll("\\*(.*?)\\*", "<i>$1</i>")         // *Italic*
            .replaceAll("(?m)^- (.*)$", "<li>$1</li>");     // - Bullet points

        previewPane.setText("<html><body style='font-family:sans-serif; padding:10px;'>" + html + "</body></html>");

        previewFrame.setLocationRelativeTo(this);
        previewFrame.setVisible(true);
    }//GEN-LAST:event_jMenuItem28ActionPerformed

