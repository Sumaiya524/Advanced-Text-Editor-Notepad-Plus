    private void jMenuItem24ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jMenuItem24ActionPerformed
        // TODO add your handling code here:
        
        javax.swing.JFileChooser fileChooser = new javax.swing.JFileChooser();

        // ১. Shudhu Image file dekhale user-er jonno shohoj hoy
        javax.swing.filechooser.FileNameExtensionFilter filter = 
            new javax.swing.filechooser.FileNameExtensionFilter("Images", "jpg", "png", "gif", "jpeg");
        fileChooser.setFileFilter(filter);

        int result = fileChooser.showOpenDialog(this);

        if (result == javax.swing.JFileChooser.APPROVE_OPTION) {
            try {
                java.io.File selectedFile = fileChooser.getSelectedFile();
                String path = selectedFile.getAbsolutePath();

                // ২. Image load kora
                javax.swing.ImageIcon icon = new javax.swing.ImageIcon(path);

                // ৩. Scale kora (Tumi jeta korecho)
                java.awt.Image img = icon.getImage();
                java.awt.Image newImg = img.getScaledInstance(200, 200, java.awt.Image.SCALE_SMOOTH);
                icon = new javax.swing.ImageIcon(newImg);

                // ৪. Current cursor position-e image-ta boshano
                output1.insertIcon(icon);

                // ৫. Image insert korar por ekta notun line ba space dewa (Optional but better UX)
                output1.getDocument().insertString(output1.getCaretPosition(), "\n", null);

            } catch (Exception e) {
                javax.swing.JOptionPane.showMessageDialog(this, "Error inserting image: " + e.getMessage());
            }
        }
        
    }//GEN-LAST:event_jMenuItem24ActionPerformed

