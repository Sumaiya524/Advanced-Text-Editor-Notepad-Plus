    void savedata() {

        JFileChooser x = new JFileChooser();

       
        javax.swing.filechooser.FileNameExtensionFilter txtFilter =
            new javax.swing.filechooser.FileNameExtensionFilter("Text Files (*.txt)", "txt");
        javax.swing.filechooser.FileNameExtensionFilter mdFilter =
            new javax.swing.filechooser.FileNameExtensionFilter("Markdown Files (*.md)", "md");
        javax.swing.filechooser.FileNameExtensionFilter logFilter =
            new javax.swing.filechooser.FileNameExtensionFilter("Log Files (*.log)", "log");

        x.addChoosableFileFilter(txtFilter);
        x.addChoosableFileFilter(mdFilter);
        x.addChoosableFileFilter(logFilter);
        x.setFileFilter(txtFilter);

        int a = x.showSaveDialog(this);

        if (a == JFileChooser.APPROVE_OPTION) {

            String fname = x.getSelectedFile().getPath();

            // Selected format detect kora
            String ext = "";

            if (x.getFileFilter() == txtFilter) {
                ext = ".txt";
            } else if (x.getFileFilter() == mdFilter) {
                ext = ".md";
            } else if (x.getFileFilter() == logFilter) {
                ext = ".log";
            }

            
            if (!fname.endsWith(ext)) {
                fname = fname + ext;
            }

            try {
                FileWriter fw = new FileWriter(fname);
                PrintWriter pw = new PrintWriter(fw);

                String s = output1.getText();
                pw.print(s);

                pw.close();

                JOptionPane.showMessageDialog(this, "File Saved Successfully!");

            } catch (IOException e) {
                JOptionPane.showMessageDialog(this, "File Save Error!");
            }
        }
    }
                            
