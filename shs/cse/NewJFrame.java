    private void jMenuItem19ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jMenuItem19ActionPerformed
        // TODO add your handling code here:
        
        
        java.time.LocalDateTime now = java.time.LocalDateTime.now();

        // 2. Format-ta ektu sundor kora (e.g., 10:30 AM 2026-04-28)
        // Tumi chaile hh:mm a bebohar kore AM/PM-o dekhaote paro
        java.time.format.DateTimeFormatter formatter = java.time.format.DateTimeFormatter.ofPattern("hh:mm a dd-MM-yyyy");
        String formattedDate = now.format(formatter);

        try {
            // 3. Document-er current cursor (caret) position-e insert kora
            int offset = output1.getCaretPosition();
            output1.getDocument().insertString(offset, formattedDate, null);

            // 4. Time insert korar por ekti extra space dewa jate porer lekha gayer opor na pore
            output1.getDocument().insertString(offset + formattedDate.length(), " ", null);

        } catch (javax.swing.text.BadLocationException e) {
            // Jodi kono karone location khuje na pay
            output1.replaceSelection(formattedDate); 
        }


    }//GEN-LAST:event_jMenuItem19ActionPerformed

    private void JMenuItem20ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_JMenuItem20ActionPerformed
        // TODO add your handling code here:
        
        String findText = JOptionPane.showInputDialog(this, "Find what:");

        if (findText != null && !findText.isEmpty()) {
            // ২. User-er kachhe jante chao ki diye replace korbe
            String replaceText = JOptionPane.showInputDialog(this, "Replace with:");

            if (replaceText != null) {
                // ৩. JTextPane theke puro lekha-ta nao
                String content = output1.getText();

                // ৪. Jodi shobdo-ta thake, tobe replace koro
                if (content.contains(findText)) {
                    // replaceAll bebohar korle shobgulo eksathe replace hoye jabe
                    String newContent = content.replaceAll(findText, replaceText);
                    output1.setText(newContent);

                    JOptionPane.showMessageDialog(this, "Replacement Done!", "Success", JOptionPane.INFORMATION_MESSAGE);
                } else {
                    JOptionPane.showMessageDialog(this, "Text not found!", "Error", JOptionPane.ERROR_MESSAGE);
                }
            }
        }
        
    }//GEN-LAST:event_JMenuItem20ActionPerformed

